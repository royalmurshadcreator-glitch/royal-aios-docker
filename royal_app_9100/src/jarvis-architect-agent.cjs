function logArchitect(entry) {
  try {
    const dir = path.dirname(ARCHITECT_HISTORY_FILE);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
    const line = JSON.stringify({ timestamp: new Date().toISOString(), ...entry }) + "\n";
    fs.appendFileSync(ARCHITECT_HISTORY_FILE, line, "utf-8");
  } catch (_) {}
}

class ArchitectAgent {
  constructor(options = {}) {
    this.id = "architect";
    this.name = "JARVIS Level-4 Full-Stack System Architect Agent";
    this.riskLevel = "LEVEL_2";
    this.capabilities = [
      "full_stack_engineering",
      "multi_file_synthesis",
      "python_node_hud_wiring",
      "end_to_end_phase_deployment",
      "autonomous_refactoring"
    ];
    this.orchestrator = options.orchestrator || null;
  }

  canHandle(command) {
    if (typeof command !== "string") return 0;
    const c = command.toLowerCase();
    const keywords = [
      "system architect", "full stack", "engineer phase", "architect agent",
      "multi file build", "build phase", "engineer feature"
    ];
    return keywords.some(k => c.includes(k)) ? 95 : 0;
  }

  status() {
    return {
      id: this.id,
      name: this.name,
      online: true,
      risk_level: this.riskLevel,
      capabilities: this.capabilities
    };
  }

  toPascalCase(str) {
    return str.charAt(0).toUpperCase() + str.slice(1).toLowerCase();
  }

  async engineerPhase(featureRequest, options = {}) {
    const result = {
      request: featureRequest,
      started_at: new Date().toISOString(),
      steps: []
    };

    try {
      // 1. Analyze Feature Goal & Names
      const match = featureRequest.match(/(?:engineer|build|create)\s+(?:phase\s+\d+\s+)?(?:a\s+|an\s+)?(\w+)/i);
      const rawName = match ? match[1].toLowerCase() : "custom" + Date.now().toString(36).slice(-4);
      const pascalName = this.toPascalCase(rawName);
      const agentId = rawName;
      const className = `${pascalName}Agent`;

      result.agent_id = agentId;
      result.class_name = className;
      result.steps.push({ phase: "1_analysis", status: "OK", message: `Engineering target: ${agentId} (${className})` });

      // 2. Python Script Blueprint
      const pyFolder = path.join(ROOT_DIR, "Agents", "Specialized");
      if (!fs.existsSync(pyFolder)) fs.mkdirSync(pyFolder, { recursive: true });
      const pyScriptPath = path.join(pyFolder, `${pascalName}Agent.py`);

      const pyCode = `"""
JARVIS Autonomous Python Engine: ${pascalName}
Generated by Full-Stack System Architect Agent
"""
import sys, os, json, time

def execute_engine_task(command_text):
    return {
        "status": "SUCCESS",
        "engine": "${pascalName}Engine",
        "command": command_text,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S")
    }

if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "default"
    print(json.dumps(execute_engine_task(cmd)))
`;
      fs.writeFileSync(pyScriptPath, pyCode, "utf-8");
      result.steps.push({ phase: "2_python_layer", status: "OK", path: pyScriptPath });

      // 3. Node.js Agent Blueprint
      const nodeAgentPath = path.join(ORCH_SRC, `${agentId}-agent.cjs`);
      const nodeCode = `const { spawn } = require("child_process");
const PY_EXE = "${PY_EXE.replace(/\\/g, "\\\\")}";
const PY_SCRIPT = "${pyScriptPath.replace(/\\/g, "\\\\")}";

class ${className} {
  constructor(options = {}) {
    this.id = "${agentId}";
    this.name = "JARVIS ${pascalName} Agent";
    this.riskLevel = "LEVEL_1";
    this.capabilities = ["${agentId}_execution", "full_stack_action"];
    this.orchestrator = options.orchestrator || null;
  }

  canHandle(command) {
    if (typeof command !== "string") return 0;
    const c = command.toLowerCase();
    return c.includes("${agentId}") ? 90 : 0;
  }

  status() {
    return {
      id: this.id,
      name: this.name,
      online: true,
      risk_level: this.riskLevel,
      capabilities: this.capabilities
    };
  }

  async execute(analysis) {
    const cmd = analysis.raw_command || analysis.command || "";
    return new Promise((resolve) => {
      const proc = spawn(PY_EXE, [PY_SCRIPT, cmd]);
      let stdout = "";
      let stderr = "";
      proc.stdout.on("data", d => stdout += d.toString());
      proc.stderr.on("data", d => stderr += d.toString());
      const timer = setTimeout(() => { proc.kill(); resolve({ success: true, output: stdout || "Timeout" }); }, 15000);
      proc.on("close", (code) => {
        clearTimeout(timer);
        try { resolve({ success: code === 0, agent: this.id, result: JSON.parse(stdout.trim()) }); }
        catch (_) { resolve({ success: code === 0, agent: this.id, output: stdout.trim() || stderr.trim() }); }
      });
    });
  }

  async createTask(analysis) {
    return { command: analysis.command, source: "${agentId}_agent", risk_level: this.riskLevel, metadata: { agent_id: this.id } };
  }
}

module.exports = { ${className} };
`;
      fs.writeFileSync(nodeAgentPath, nodeCode, "utf-8");
      result.steps.push({ phase: "3_node_layer", status: "OK", path: nodeAgentPath });

      // 4. Runtime Registration
      let runtimeContent = fs.readFileSync(RUNTIME_FILE, "utf-8");
      const requireStmt = `const { ${className} } = require("./${agentId}-agent.cjs");`;
      const registerStmt = `  registry.register(new ${className}({ orchestrator }));`;

      if (!runtimeContent.includes(requireStmt)) {
        const lastRequireMatch = runtimeContent.match(/const \{ [^}]+\ } = require\("\.\/[^"]+"\);/g);
        if (lastRequireMatch && lastRequireMatch.length) {
          const lastReq = lastRequireMatch[lastRequireMatch.length - 1];
          runtimeContent = runtimeContent.replace(lastReq, `${lastReq}\n${requireStmt}`);
        }
        const lastRegMatch = runtimeContent.match(/registry\.register\(new [^)]+\);\r?\n/g);
        if (lastRegMatch && lastRegMatch.length) {
          const lastReg = lastRegMatch[lastRegMatch.length - 1];
          runtimeContent = runtimeContent.replace(lastReg, `${lastReg}${registerStmt}\n`);
        }
        fs.writeFileSync(RUNTIME_FILE, runtimeContent, "utf-8");
        result.steps.push({ phase: "4_runtime_wiring", status: "OK" });
      }

      // 5. REST API Route Injection
      let serverContent = fs.readFileSync(SERVER_FILE, "utf-8");
      const routeCheck = `if ((route === "${agentId}" || route === "jarvis/${agentId}")`;
      if (!serverContent.includes(routeCheck)) {
        const routeCode = `
  // Full-Stack Architect Autogenerated Route: ${agentId}
  if ((route === "${agentId}" || route === "jarvis/${agentId}") && req.method === "POST") {
    try {
      const raw = await readBody(req);
      const payload = raw && raw.length ? JSON.parse(raw.toString()) : {};
      const command = typeof payload.command === "string" ? payload.command.trim() : "";
      const result = await royalJarvisRuntime.brain.dispatch(command || "${agentId} action");
      return send(res, 200, { ok: true, result });
    } catch(err) {
      return send(res, 500, { ok: false, error: err.message });
    }
  }
`;
        const esIdx = serverContent.indexOf("// Emergency stop");
        if (esIdx !== -1) {
          serverContent = serverContent.substring(0, esIdx) + routeCode + "\n      " + serverContent.substring(esIdx);
          fs.writeFileSync(SERVER_FILE, serverContent, "utf-8");
          result.steps.push({ phase: "5_api_wiring", status: "OK" });
        }
      }

      // 6. Syntax Checks
      execSync(`node --check "${nodeAgentPath}"`, { stdio: "pipe" });
      execSync(`node --check "${SERVER_FILE}"`, { stdio: "pipe" });
      result.steps.push({ phase: "6_syntax_checks", status: "OK" });

      result.status = "SUCCESS";
      result.message = `Full-stack phase for '${agentId}' engineered across Python, Node, Runtime, and Server APIs.`;
      result.completed_at = new Date().toISOString();
      logArchitect(result);
      return result;

    } catch (err) {
      result.status = "FAILED";
      result.error = err.message;
      result.steps.push({ phase: "ERROR", status: "FAILED", message: err.message });
      logArchitect(result);
      return result;
    }
  }

  async execute(analysis) {
    const cmd = analysis.raw_command || analysis.command || "";
    return await this.engineerPhase(cmd);
  }

  async createTask(analysis) {
    return { command: analysis.command, source: "architect_agent", risk_level: this.riskLevel, metadata: { agent_id: this.id } };
  }
}

function createArchitectAgent(options) {
  return new ArchitectAgent(options);
}

module.exports = { ArchitectAgent, createArchitectAgent };

